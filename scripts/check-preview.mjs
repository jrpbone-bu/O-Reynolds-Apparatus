import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror', error=>errors.push(error.message));
await page.goto('http://localhost:5173/',{waitUntil:'networkidle'});
await page.locator('#loading').waitFor({state:'hidden'});
await page.screenshot({path:'artifacts/desktop.png'});
await page.getByTitle('Automatically rotate model').click();
if(await page.locator('#rotate').getAttribute('aria-pressed')!=='true')throw Error('Auto-rotate did not activate');
await page.getByTitle('View apparatus from the front').click();
if(await page.locator('#view-label').innerText()!=='FRONT VIEW')throw Error('Front view did not activate');
await page.getByRole('button',{name:'Zoom in',exact:true}).click();
await page.screenshot({path:'artifacts/detail.png'});
await page.getByTitle('Reset camera').click();
await page.locator('#reference-open').click();
if(!await page.locator('dialog').isVisible())throw Error('Reference dialog did not open');
await page.getByRole('button',{name:'Close reference'}).click();
await page.close();
const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const phone=await mobile.newPage();
phone.on('pageerror', error=>errors.push(error.message));
phone.on('console', msg=>{if(msg.type()==='error')console.log('Mobile console:',msg.text());});
await phone.goto('http://localhost:5173/',{waitUntil:'networkidle'});
await phone.locator('#loading').waitFor({state:'hidden',timeout:60000});
await phone.screenshot({path:'artifacts/mobile.png'});
if(await phone.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Mobile horizontal overflow');
await phone.getByRole('button',{name:'Zoom in',exact:true}).tap();
await phone.getByTitle('Reset camera').tap();
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: desktop and mobile WebGL render, controls, reference dialog, no page errors or mobile overflow.');
await browser.close();
